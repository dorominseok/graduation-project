-- =====================================================
-- V4: 세트 저장 멱등 키
-- 근거: 「API 명세서」 6.4 「멱등 처리」, 9.1 / LOG-13
-- =====================================================

-- 요청이 서버에 도달해 저장까지 끝난 뒤 응답만 유실되면, 클라이언트는 실패로
-- 판단해 재전송한다. 멱등 키가 없으면 같은 세트가 2행이 되고, 그것은 곧 볼륨
-- 과대 집계 — 부족한 부위가 충분한 것으로 올라가는 '약점을 놓치는 방향'의
-- 오판이다(LOG-02·LOG-09가 경계해온 방향). 오프라인 기능이 없어도 발생한다.
-- UC-02-01 예외 흐름 6a의 "재시도를 안내한다"에서 사용자가 재시도를 누르면 그대로다.
--
-- 클라이언트가 완료 체크 시점에 UUID를 만들어 보내고, 재전송에는 같은 값을 쓴다.
-- 서버는 이미 있는 키면 저장하지 않고 기존 세트를 200 OK로 돌려준다(6.4).

ALTER TABLE workout_sets ADD COLUMN client_set_id UUID;

-- 기존 행이 없으므로(9월 구현 착수 전) 백필 없이 NOT NULL로 올린다.
-- 값이 비면 멱등 판정 자체가 성립하지 않으므로 NULL을 허용하지 않는다.
ALTER TABLE workout_sets ALTER COLUMN client_set_id SET NOT NULL;

-- 애플리케이션이 "이미 있나?"를 확인하는 사이에 두 요청이 동시에 들어와도
-- DB가 두 번째를 거부한다. 최종 방어선은 코드가 아니라 이 제약이다.
--
-- 키의 유효 범위를 세션 안으로 한정한 이유: 클라이언트가 만드는 값이므로
-- 전역 유일성을 신뢰할 근거가 없고, 세션이 다르면 같은 값이 와도 서로 다른
-- 세트다. 조회도 항상 세션 단위로 일어난다(6.4는 세션 하위 경로다).
ALTER TABLE workout_sets ADD CONSTRAINT uq_workout_sets_client_set_id
    UNIQUE (session_id, client_set_id);
