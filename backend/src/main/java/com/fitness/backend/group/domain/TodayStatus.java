package com.fitness.backend.group.domain;

/**
 * 그룹 화면의 "오늘 운동했나". 손으로 체크하지 않고 기록에서 정한다(LOG-38).
 *
 * <p>체크를 따로 두면 기록과 두 번 입력해야 하고, "체크는 했는데 기록이 없다" 같은
 * 어긋남이 생긴다. 기록해야 그룹에 뜨므로 기록을 이어 가게 하는 장치도 된다.
 *
 * <p>"운동 중"은 두지 않는다. 그룹에는 <b>끝난 운동만</b> 보인다 — 진행 중인 기록은 보는
 * 시점마다 세트 수가 달라 보이고, 운동하는 사람에게도 하는 중에 다 보이는 건 부담이다.
 */
public enum TodayStatus {
    /** 오늘 날짜로 완료한 운동이 있다. 사후 입력도 포함한다 */
    DONE,
    NONE
}
