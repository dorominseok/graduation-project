package com.fitness.backend.group.domain;

/**
 * 그룹 화면의 "오늘 운동했나". 손으로 체크하지 않고 기록에서 정한다.
 *
 * <p>체크를 따로 두면 기록과 두 번 입력해야 하고, "체크는 했는데 기록이 없다" 같은
 * 어긋남이 생긴다. 기록해야 그룹에 뜨므로 기록을 이어 가게 하는 장치도 된다.
 *
 * <p>"운동 중"은 두지 않는다. 종료가 없어 운동 중과 운동 끝을 가를 수 없고, 오늘 세트가
 * 하나라도 있으면 오늘 운동한 것이다.
 */
public enum TodayStatus {
    /** 오늘 기록에 세트가 있다. 사후 입력도 포함한다 */
    DONE,
    NONE
}
